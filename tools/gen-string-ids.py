#!/usr/bin/env python3
"""Writes src/data/string-ids.js from the C++ port's strings.h: the names of the game's strings and
their DATA.OVL offsets (names only - the text itself is read from DATA.OVL at run time), and the
list of text regions from strings.cpp.

    python3 tools/gen-string-ids.py ../ultima5_sdl/src
"""
import re, sys
src = sys.argv[1] if len(sys.argv) > 1 else '../ultima5_sdl/src'
h = open(src + '/strings.h').read()
ids = re.findall(r'^\s+(\w+) = 0x([0-9A-F]{4}),', h, flags=re.M)
c = open(src + '/strings.cpp').read()
regions = re.findall(r'\{0x([0-9A-F]{4}), 0x([0-9A-F]{4})\}', c)
out = ['// string-ids.js - GENERATED by tools/gen-string-ids.py from the C++ port: do not edit.',
       '// The game\'s strings by name; each value is the string\'s offset in DATA.OVL\'s data segment,',
       '// and the name ends with it. The text is read from DATA.OVL (strings.js).', '',
       'export const S = Object.freeze({', '  NONE: 0,']
out += ['  %s: 0x%s,' % (n, v) for n, v in ids]
out += ['});', '', '/** Where DATA.OVL keeps text: [start, end) data-segment offsets. */',
        'export const TEXT_REGIONS = Object.freeze([']
out += ['  [0x%s, 0x%s],' % (a, b) for a, b in regions]
out += [']);', '']
open('src/data/string-ids.js', 'w').write('\n'.join(out))
print(len(ids), 'ids,', len(regions), 'regions')
